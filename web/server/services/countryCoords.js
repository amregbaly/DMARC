/**
 * Parses and extracts [latitude, longitude] from diverse OpenSearch geo_point representations.
 * Handles {lat, lon}, {lat, lng}, [lon, lat] (GeoJSON array), and "lat,lon" strings.
 */
function parseGeoPoint(location) {
  if (!location) return null;

  if (typeof location === 'object' && !Array.isArray(location)) {
    const lat = Number(location.lat);
    const lon = Number(location.lon ?? location.lng);
    if (!Number.isNaN(lat) && !Number.isNaN(lon) && lat >= -90 && lat <= 90 && lon >= -180 && lon <= 180) {
      return [lat, lon];
    }
  }

  if (Array.isArray(location) && location.length >= 2) {
    // OpenSearch/GeoJSON index standard: [lon, lat]
    // If location[0] is within -180..180 and location[1] within -90..90
    const lon = Number(location[0]);
    const lat = Number(location[1]);
    if (!Number.isNaN(lat) && !Number.isNaN(lon) && lat >= -90 && lat <= 90 && lon >= -180 && lon <= 180) {
      return [lat, lon];
    }
  }

  if (typeof location === 'string') {
    const parts = location.split(',').map(s => Number(s.trim()));
    if (parts.length === 2 && !Number.isNaN(parts[0]) && !Number.isNaN(parts[1])) {
      const lat = parts[0];
      const lon = parts[1];
      if (lat >= -90 && lat <= 90 && lon >= -180 && lon <= 180) {
        return [lat, lon];
      }
    }
  }

  return null;
}

/**
 * Resolves coordinates for an IP/sender based on optional explicit geo location or country code/name.
 *
 * @param {string} countryInput - ISO alpha-2 country code (e.g. 'CL', 'US') or country name
 * @param {any} [explicitLocation] - Explicit geo_point from OpenSearch source
 * @param {boolean} [addJitter=true] - Whether to apply minor jitter so co-located IPs don't overlap exactly
 * @returns {{ lat: number, lng: number } | null} Valid coordinates or null if unknown
 */
export function resolveCoordinates(countryInput, explicitLocation = null, addJitter = true) {
  // 1. Try explicit OpenSearch GeoIP location first
  const parsed = parseGeoPoint(explicitLocation);
  if (parsed) {
    return {
      lat: Number(parsed[0].toFixed(5)),
      lng: Number(parsed[1].toFixed(5))
    };
  }

  // 2. Lookup by country code or name
  if (!countryInput || typeof countryInput !== 'string') {
    return null;
  }

  const clean = countryInput.trim().toUpperCase();
  let code = clean;

  if (clean.length !== 2) {
    code = COUNTRY_NAME_MAP[clean] || null;
  }

  if (!code || !COUNTRY_COORDS[code]) {
    return null;
  }

  const base = COUNTRY_COORDS[code];
  const jitterLat = addJitter ? (Math.random() - 0.5) * 1.5 : 0;
  const jitterLng = addJitter ? (Math.random() - 0.5) * 1.5 : 0;

  // Clamp within valid Earth lat [-85, 85], lng [-180, 180]
  const lat = Math.max(-85, Math.min(85, Number((base[0] + jitterLat).toFixed(5))));
  const lng = Math.max(-180, Math.min(180, Number((base[1] + jitterLng).toFixed(5))));

  return { lat, lng };
}
